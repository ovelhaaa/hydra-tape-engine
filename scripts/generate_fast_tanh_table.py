#!/usr/bin/env python3
"""Regenerate dsp/core/fast_tanh_table.inc.

The Hydra magnetic stage evaluates tanh through a 1025-entry lookup table.
The table used to be filled at construction time with std::tanh, which is a
platform libm call: glibc, the Windows UCRT and musl/Emscripten disagree on the
last bit of some results. Quantising those results to float turned that
last-bit disagreement into 84 differing table entries, and that was the first
stage where Native and WASM audio diverged (Phase 6.4, issue #48).

This generator removes the host dependency: every value is computed with
60-digit decimal arithmetic and rounded exactly once to float32, so the emitted
bit patterns are identical on every platform. The table is a set of constants,
not a runtime approximation, so the DSP cost is unchanged and ESP32 flash is
spent instead of 4 KiB of RAM.

Run: python scripts/generate_fast_tanh_table.py
"""
from decimal import Decimal, getcontext
from pathlib import Path
import struct

N = 1024
PRECISION = 60


def float32_bits(value: float) -> int:
    return struct.unpack("<I", struct.pack("<f", value))[0]


def main() -> int:
    getcontext().prec = PRECISION
    path = Path(__file__).resolve().parents[1] / "dsp" / "core" / "fast_tanh_table.inc"
    rows = []
    for i in range(N + 1):
        x = Decimal(-4) + Decimal(8) * Decimal(i) / Decimal(N)
        e = (2 * x).exp()
        t = (e - 1) / (e + 1)
        rows.append(struct.unpack("<f", struct.pack("<f", float(t)))[0])

    lines = [
        "// Generated by scripts/generate_fast_tanh_table.py -- do not edit by hand.",
        "// tanh over [-4, 4] in %d equal steps, evaluated in %d-digit decimal" % (N, PRECISION),
        "// arithmetic and rounded exactly once to float32. Host instructions and",
        "// libm implementations therefore cannot change these bits (issue #48).",
        "constexpr int kFastTanhTableSize = %d;" % N,
        "constexpr float kFastTanhTable[kFastTanhTableSize + 1] = {",
    ]
    for i, value in enumerate(rows):
        lines.append("    %s," % float.hex(value))
    lines.append("};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(rows)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
